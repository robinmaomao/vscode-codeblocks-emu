// 验证 A4 generatedFiles 自动生成文件机制：applyGeneratedFiles 建立 生成器→生成文件 关系
// 复刻 cbProject::AddFile GenFilesHackMap 语义（vscode 无关，mock Compiler）
const path = require('path');
const { applyGeneratedFiles } = require('./dist/build/generatedFiles.js');
const { fileTypeOf } = require('./dist/model/fileTypes.js');

function mkCompiler(gens) {
  return {
    programs: { C: 'gcc', CPP: 'g++', LD: 'g++', LIB: 'ar', WINDRES: '' },
    commands: {
      0: [], // 占位（CommandType 枚举实际值由 dist 决定，下面用真实值）
    },
  };
}

// 读取真实 CommandType 枚举值
const types = require('./dist/model/types.js');
const CT = types.CommandType;

function mkProject() {
  const project = {
    title: 't', basePath: 'C:/proj', commonTopLevelPath: 'C:/proj', pchMode: 1, extendedObjNames: false,
    filename: 'C:/proj/t.cbp', compilerId: 'qt',
    compilerOptions: [], linkerOptions: [], resourceCompilerOptions: [],
    includeDirs: [], libDirs: [], resourceIncludeDirs: [], linkLibs: [],
    virtualTargets: [], virtualFolders: [], commandsBeforeBuild: [], commandsAfterBuild: [],
    buildScripts: [], notes: '', showNotesOnLoad: false, envVars: [], alwaysRunPostBuildSteps: false,
    files: [],
    buildTargets: [{ title: 'Debug', files: [] }],
    extensions: null,
  };
  return project;
}

function mkFile(project, rel) {
  return {
    relativeFilename: rel,
    relativeToCommonTopLevelPath: rel,
    absolutePath: path.join(project.basePath, rel),
    buildTargets: ['Debug'],
    explicitTargets: false,
    compilerVar: 'CC',
    compile: true,
    link: true,
    customBuildCommands: {},
    weight: 50,
    virtualFolder: '',
    generatedFiles: [],
  };
}

let pass = 0, fail = 0;
function check(name, cond) {
  if (cond) { pass++; console.log('OK  ' + name); }
  else { fail++; console.log('FAIL ' + name); }
}

// --- 场景 1：.ui 文件（非源类型）声明生成 moc_$file_name.cpp ---
{
  const project = mkProject();
  const ui = mkFile(project, 'forms/main.ui');
  project.files.push(ui);
  project.buildTargets[0].files.push(ui);

  const compiler = {
    programs: { C: 'gcc', CPP: 'g++', LD: 'g++', LIB: 'ar', WINDRES: '' },
    commands: {
      [CT.CompileObjectCmd]: [
        { command: 'uic $file -o $file_dir/$file_name.h', extensions: ['ui'], generatedFiles: ['moc_$file_name.cpp'] },
      ],
    },
  };
  applyGeneratedFiles(project, () => compiler);

  check('生成文件加入 project.files', project.files.some((f) => f.relativeFilename === 'forms/moc_main.cpp'));
  check('生成器 generatedFiles 记录', ui.generatedFiles.length === 1 && ui.generatedFiles[0] === 'forms/moc_main.cpp');
  const gen = project.files.find((f) => f.relativeFilename === 'forms/moc_main.cpp');
  check('生成文件 autoGeneratedBy 指向生成器', gen && gen.autoGeneratedBy === 'forms/main.ui');
  check('生成文件 compile=true（.cpp 默认）', gen && gen.compile === true);
  check('生成文件 link=true（.cpp 默认）', gen && gen.link === true);
  check('生成文件归属同一目标', gen && gen.buildTargets.includes('Debug') && project.buildTargets[0].files.includes(gen));
}

// --- 场景 2：宏展开 $file_ext / $file_basename / $file ---
{
  const project = mkProject();
  const ui = mkFile(project, 'ui/panel.ui');
  project.files.push(ui);

  const compiler = {
    programs: { C: 'gcc', CPP: 'g++', LD: 'g++', LIB: 'ar', WINDRES: '' },
    commands: {
      [CT.CompileObjectCmd]: [
        { command: 'gen', extensions: ['ui'], generatedFiles: ['x_$file_basename.$file_ext.cpp', 'y_$file.cpp'] },
      ],
    },
  };
  applyGeneratedFiles(project, () => compiler);

  check('$file_basename/$file_ext 展开', project.files.some((f) => f.relativeFilename === 'ui/x_panel.ui.cpp'));
  check('$file 展开（含扩展名）', project.files.some((f) => f.relativeFilename === 'ui/y_panel.ui.cpp'));
}

// --- 场景 3：无 gen 工具的编译器不产生关系 ---
{
  const project = mkProject();
  const c = mkFile(project, 'src/main.c');
  project.files.push(c);

  const compiler = {
    programs: { C: 'gcc', CPP: 'g++', LD: 'g++', LIB: 'ar', WINDRES: '' },
    commands: { [CT.CompileObjectCmd]: [{ command: 'gcc -c $file', extensions: [], generatedFiles: [] }] },
  };
  applyGeneratedFiles(project, () => compiler);
  check('无 gen 工具不产生生成文件', project.files.length === 1 && c.generatedFiles.length === 0);
}

// --- 场景 4：重复调用幂等 ---
{
  const project = mkProject();
  const ui = mkFile(project, 'a.ui');
  project.files.push(ui);
  const compiler = {
    programs: { C: 'gcc', CPP: 'g++', LD: 'g++', LIB: 'ar', WINDRES: '' },
    commands: { [CT.CompileObjectCmd]: [{ command: 'gen', extensions: ['ui'], generatedFiles: ['moc_a.cpp'] }] },
  };
  applyGeneratedFiles(project, () => compiler);
  applyGeneratedFiles(project, () => compiler);
  check('重复调用幂等', project.files.filter((f) => f.relativeFilename === 'moc_a.cpp').length === 1);
}

console.log('汇总: ' + pass + ' pass, ' + fail + ' fail');
process.exit(fail ? 1 : 0);
