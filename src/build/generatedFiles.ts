/**
 * generatedFiles 自动生成文件机制 —— 对齐 cbProject::AddFile 的 GenFilesHackMap（cbproject.cpp:815-978）。
 *
 * Code::Blocks 语义：
 * 1. 生成关系不写在 .cbp（保存时跳过，projectloader.cpp:1794-1795）；
 * 2. 项目加载/添加文件时，若文件所属编译器的 CompileObject/CompileResource 工具声明了
 *    `gen="file1;file2"`（扩展 optionsLoader 已解析到 CompilerTool.generatedFiles），
 *    则为每个生成名建立「生成器 → 生成文件」关系并把生成文件加入项目；
 * 3. 生成文件名支持 $file_basename/$file_name/$file_dir/$file_ext/$file 宏（对齐 AddFile 内替换），
 *    生成文件路径 = 源文件所在目录 + 生成名；
 * 4. 生成文件继承生成器的目标归属与默认 compile/link（按文件类型）。
 */
import * as path from 'path';
import { Project, ProjectFile, CommandType } from '../model/types';
import { Compiler, CompilerTool } from '../compiler/compiler';
import { fileTypeOf, fileExt, FileType, defaultCompilerVar, defaultCompile, defaultLink } from '../model/fileTypes';

function toUnix(p: string): string {
  return p.replace(/\\/g, '/');
}

/** 按扩展名匹配编译工具（空扩展 = 通配兜底，对齐 CommandGenerator.getCommandTemplate） */
function findTool(tools: CompilerTool[] | undefined, ext: string): CompilerTool | undefined {
  if (!tools || tools.length === 0) return undefined;
  let catchAll: CompilerTool | undefined;
  for (const t of tools) {
    if (t.extensions.length === 0) {
      catchAll = t;
      continue;
    }
    if (t.extensions.includes(ext)) return t;
  }
  return catchAll;
}

/**
 * 为项目建立 生成器 → 生成文件 关系（幂等：重复调用前先清理旧关系）。
 * 在 openProject 解析 .cbp 之后调用。
 */
export function applyGeneratedFiles(project: Project, getCompiler: (id: string) => Compiler | undefined): void {
  const compiler = getCompiler(project.compilerId);
  if (!compiler) return;

  // 清理上次建立的关系（防止重复解析叠加）
  for (const f of project.files) f.generatedFiles = [];
  project.files = project.files.filter((f) => !f.autoGeneratedBy);

  const files = [...project.files];
  for (const pf of files) {
    const isRes = fileTypeOf(pf.relativeFilename) === FileType.Resource;
    const ct = isRes ? CommandType.CompileResourceCmd : CommandType.CompileObjectCmd;
    const tool = findTool(compiler.commands[ct], fileExt(pf.relativeFilename));
    if (!tool || tool.generatedFiles.length === 0) continue;

    const dir = path.dirname(pf.absolutePath);
    const ext = fileExt(pf.relativeFilename);
    const baseName = path.basename(pf.relativeFilename); // 含扩展名（$file）
    const baseStem = baseName.replace(/\.[^.]+$/, '');   // 不含扩展名（$file_name）

    for (const gen of tool.generatedFiles) {
      let name = gen
        .replace(/\$file_basename/g, baseStem)
        .replace(/\$file_name/g, baseStem)
        .replace(/\$file_dir/g, toUnix(dir))
        .replace(/\$file_ext/g, ext)
        .replace(/\$file/g, baseName);
      // 注：Code::Blocks 此处还做 ReplaceMacros（$(PROJECT_DIR) 等），生成名含此类宏的场景极罕见，暂不展开
      const abs = path.resolve(dir, name);
      const rel = toUnix(path.relative(project.basePath, abs));
      if (project.files.some((f) => f.relativeFilename === rel)) continue; // 防重复

      const genFile: ProjectFile = {
        relativeFilename: rel,
        relativeToCommonTopLevelPath: rel,
        absolutePath: abs,
        buildTargets: [...pf.buildTargets],
        explicitTargets: pf.explicitTargets,
        compilerVar: defaultCompilerVar(rel),
        compile: defaultCompile(rel),
        link: defaultLink(rel),
        customBuildCommands: {},
        weight: 50,
        virtualFolder: '',
        generatedFiles: [],
        autoGeneratedBy: pf.relativeFilename,
      };
      project.files.push(genFile);
      pf.generatedFiles.push(rel);
      // 同步目标归属（供编译单元收集与 clean 使用）
      for (const t of project.buildTargets) {
        if (pf.buildTargets.includes(t.title) && !t.files.includes(genFile)) {
          t.files.push(genFile);
        }
      }
    }
  }
}
